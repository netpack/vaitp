def load_dotenv(path: str) -> None:
    """Populate os.environ from a .env file without overwriting real env vars."""
    if not os.path.isfile(path):
        return
    with open(path, encoding="utf-8", errors="replace") as fh:
        for line in fh:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, _, value = line.partition("=")
            os.environ.setdefault(key.strip(), value.strip().strip("'\""))


def load_db_config(db_config: str | None) -> dict[str, str]:
    """Resolve MySQL credentials from --db-config, then the environment."""
    cfg: dict[str, str] = {}
    if db_config:
        import configparser

        parser = configparser.ConfigParser()
        parser.read(db_config)
        section = "client" if parser.has_section("client") else parser.sections()[0]
        cfg = {
            "host": parser.get(section, "host", fallback=""),
            "user": parser.get(section, "user", fallback=""),
            "password": parser.get(section, "password", fallback=""),
            "database": parser.get(section, "database", fallback=""),
        }

    cfg = {
        "host": cfg.get("host") or os.environ.get("MYSQL_HOST", ""),
        "user": cfg.get("user") or os.environ.get("MYSQL_USER", ""),
        "password": cfg.get("password") or os.environ.get("MYSQL_PASSWORD", ""),
        "database": cfg.get("database") or os.environ.get("MYSQL_DATABASE", ""),
    }
    missing = [k for k, v in cfg.items() if not v]
    if missing:
        sys.exit(
            f"Missing MySQL settings: {', '.join(missing)}.\n"
            "Export MYSQL_HOST / MYSQL_USER / MYSQL_PASSWORD / MYSQL_DATABASE, add them "
            "to the .env in the framework root, or pass --db-config <my.cnf>.\n"
            "(The same values rag_updater.py uses.)"
        )
    return cfg


