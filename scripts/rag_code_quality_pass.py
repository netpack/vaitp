def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        description="Audit and rewrite VAITP code samples for RAG suitability using Claude Opus 5.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    p.add_argument("--apply", action="store_true",
                   help="write to the database (default is a dry run)")
    p.add_argument("--limit", type=int, help="process at most N records")
    p.add_argument("--ids", help="comma-separated record IDs to process (or restore)")
    p.add_argument("--where", default="Ignored=0 AND isPython=1",
                   help="SQL filter; defaults to the rows the FAISS index actually uses")
    p.add_argument("--ascending", action="store_true",
                   help="oldest record first (default is newest first)")
    p.add_argument("--resume", action="store_true",
                   help="skip IDs already decided in the audit log")
    p.add_argument("--only-suspect", action="store_true",
                   help="only send records the deterministic pre-scan flags (cheap triage pass)")
    p.add_argument("--audit-log", default=DEFAULT_AUDIT_LOG,
                   help=f"JSONL audit trail (default: {DEFAULT_AUDIT_LOG})")
    p.add_argument("--files-dir",
                   help="also write rewritten samples as {dir}/injectable/{id}_1.py and "
                        "{dir}/noninjectable/{id}_1.py")
    p.add_argument("--daily-quota", type=int, default=10,
                   help="stop after N model decisions per calendar day, counted from the "
                        "audit log so restarts and re-runs respect it (default: 10; 0 = no cap)")
    p.add_argument("--daemon", action="store_true",
                   help="instead of exiting when the daily quota is reached, sleep until "
                        "the next local midnight and carry on; spreads the day's records "
                        "evenly unless --min-interval says otherwise")
    p.add_argument("--min-interval", type=float, default=None,
                   help="minimum seconds between requests (default: 60, or the even "
                        "spread across the day when --daemon is used with a quota)")
    p.add_argument("--rpm", type=float, default=3.0,
                   help="rolling requests-per-minute ceiling (default: 3)")
    p.add_argument("--effort", default="high", choices=["low", "medium", "high", "xhigh", "max"],
                   help="output_config.effort for the model (default: high)")
    p.add_argument("--max-tokens", type=int, default=16000)
    p.add_argument("--no-fallbacks", action="store_true",
                   help="do not request server-side refusal fallbacks")
    p.add_argument("--db-config", help="my.cnf-style file holding the MySQL credentials")
    p.add_argument("--restore", metavar="AUDIT_LOG",
                   help="restore the `before` snapshots from an audit log and exit")
    return p


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)

    load_dotenv(os.path.join(VAITP_PATH, ".env"))
    cfg = load_db_config(args.db_config)

    if args.restore:
        return restore(args, cfg)

    if not os.environ.get("ANTHROPIC_API_KEY"):
        sys.exit("ANTHROPIC_API_KEY is not set (env or .env in the framework root).")

    import anthropic

    where = args.where
    if args.ids:
        wanted = ",".join(str(int(x)) for x in args.ids.split(","))
        where = f"({where}) AND ID IN ({wanted})"

    conn = connect(cfg)
    try:
        records = fetch_records(conn, where, args.limit, args.ascending)
    finally:
        conn.close()

    if args.resume:
        done = processed_ids(args.audit_log)
        before_count = len(records)
        records = [r for r in records if r["ID"] not in done]
        print(f"Resume: skipping {before_count - len(records)} already-decided record(s).")

    if args.only_suspect:
        before_count = len(records)
        records = [
            r for r in records
            if prescan(r.get("VulnerableCodeSample") or "",
                       r.get("PatchedCodeSample") or "") != ["nothing"]
        ]
        print(f"Triage: {len(records)} of {before_count} record(s) flagged by the pre-scan.")

    if not records:
        print("Nothing to do.")
        return 0

    # Pacing. With a daily quota in daemon mode the sensible spacing is the day divided by
    # the quota, so the run trickles rather than firing a burst and idling for 23 hours.
    quota = max(args.daily_quota, 0)
    if args.min_interval is not None:
        min_interval = args.min_interval
    elif args.daemon and quota:
        min_interval = 86400.0 / quota
    else:
        min_interval = 60.0

    done_today = count_done_today(args.audit_log) if quota else 0

    mode = "APPLY (writing to the database)" if args.apply else "DRY RUN (no writes)"
    print(f"\n{'=' * 78}")
    print(f"VAITP RAG code-sample pass — {mode}")
    print(f"  model        : {MODEL} (effort={args.effort}, adaptive thinking)")
    print(f"  records      : {len(records)} remaining "
          f"({'oldest' if args.ascending else 'newest'} first)")
    if quota:
        print(f"  daily quota  : {quota}/day, {done_today} already done today "
              f"-> {max(quota - done_today, 0)} left in this day")
    else:
        print("  daily quota  : none")
    print(f"  pacing       : >={min_interval:.0f}s between calls, <={args.rpm:.0f} req/min")
    print(f"  mode         : {'daemon (sleeps through to the next day)' if args.daemon else 'single batch (exits when the quota is spent)'}")
    print(f"  audit log    : {args.audit_log}")
    if quota:
        print(f"  est. finish  : ~{-(-len(records) // quota)} day(s) at {quota}/day")
    else:
        est_hours = len(records) * max(min_interval, 60.0 / max(args.rpm, 0.01)) / 3600.0
        print(f"  est. runtime : {est_hours:.1f}h at this pacing (excluding model latency)")
    print(f"{'=' * 78}\n")

    auditor = Auditor(
        client=anthropic.Anthropic(max_retries=0, timeout=1800.0),
        limiter=RateLimiter(min_interval, args.rpm),
        effort=args.effort,
        max_tokens=args.max_tokens,
        use_fallbacks=not args.no_fallbacks,
    )

    conn = connect(cfg)
    tally = {"pass": 0, "rewrite": 0, "refused": 0, "failed": 0, "error": 0}
    started = time.time()

    try:
        for index, record in enumerate(records, start=1):
            if quota and done_today >= quota:
                if not args.daemon:
                    print(f"\nDaily quota of {quota} reached — stopping. "
                          "Re-run with --resume tomorrow (or add --daemon to keep going).")
                    break
                sleep_until_next_midnight()
                done_today = count_done_today(args.audit_log)

            record_id = record["ID"]
            label = f"[{index}/{len(records)}] ID {record_id} ({record.get('CVE')})"
            print(label)

            try:
                result = auditor.audit(record)
            except KeyboardInterrupt:
                raise
            except Exception as exc:  # noqa: BLE001 — one bad row must not kill the run
                tally["error"] += 1
                print(f"  ERROR {exc.__class__.__name__}: {exc}")
                append_audit(args.audit_log, {
                    "id": record_id, "cve": record.get("CVE"), "status": "error",
                    "detail": f"{exc.__class__.__name__}: {exc}",
                    "timestamp": datetime.now(timezone.utc).isoformat(),
                })
                continue

            status = result["status"]
            tally[status] = tally.get(status, 0) + 1
            if status in QUOTA_STATUSES:
                done_today += 1

            entry: dict[str, Any] = {
                "id": record_id,
                "cve": record.get("CVE"),
                "status": status,
                "issues": result.get("issues", []),
                "notes": result.get("notes", result.get("detail", "")),
                "applied": False,
                "timestamp": datetime.now(timezone.utc).isoformat(),
            }

            if status == "pass":
                print("  pass")
            elif status == "rewrite":
                entry["before"] = {
                    "vulnerable": record.get("VulnerableCodeSample") or "",
                    "patched": record.get("PatchedCodeSample") or "",
                }
                entry["after"] = {
                    "vulnerable": result["vulnerable_code"],
                    "patched": result["patched_code"],
                }
                shrink = (
                    len(entry["before"]["vulnerable"]) + len(entry["before"]["patched"]),
                    len(entry["after"]["vulnerable"]) + len(entry["after"]["patched"]),
                )
                print(f"  rewrite [{', '.join(result.get('issues', [])) or 'unspecified'}]"
                      f"  {shrink[0]} -> {shrink[1]} chars")
                print(f"    {result.get('notes', '')}")
                if args.apply:
                    update_record(conn, record_id,
                                  result["vulnerable_code"], result["patched_code"])
                    if args.files_dir:
                        write_sample_files(args.files_dir, record_id,
                                           result["vulnerable_code"], result["patched_code"])
                    entry["applied"] = True
            else:
                print(f"  {status}: {result.get('detail', '')}")

            append_audit(args.audit_log, entry)

            if index % 10 == 0 or index == len(records):
                elapsed = (time.time() - started) / 60.0
                print(f"  -- {index} done in {elapsed:.0f} min | "
                      f"pass {tally['pass']} rewrite {tally['rewrite']} "
                      f"refused {tally['refused']} failed {tally['failed']} error {tally['error']} | "
                      f"{auditor.usage.input_tokens:,} in / {auditor.usage.output_tokens:,} out "
                      f"(~${auditor.usage.cost_usd():.2f})")

    except KeyboardInterrupt:
        print("\nInterrupted. Re-run with --resume to continue where this left off.")
    finally:
        conn.close()

    print(f"\n{'=' * 78}")
    print(f"Done in {(time.time() - started) / 60.0:.0f} min — "
          f"pass {tally['pass']}, rewrite {tally['rewrite']}, refused {tally['refused']}, "
          f"failed {tally['failed']}, error {tally['error']}")
    print(f"Tokens: {auditor.usage.input_tokens:,} in + {auditor.usage.cache_read:,} cache-read "
          f"+ {auditor.usage.cache_write:,} cache-write / {auditor.usage.output_tokens:,} out "
          f"over {auditor.usage.requests} requests — approx ${auditor.usage.cost_usd():.2f}")
    print(f"Audit trail: {args.audit_log}")
    if not args.apply and tally["rewrite"]:
        print("Dry run — nothing was written. Re-run with --apply to commit.")
    print(f"{'=' * 78}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
