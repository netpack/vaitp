#!/usr/bin/env python3
"""
RAG-suitability audit and rewrite pass over the VAITP code samples.

Every record in `python_vulnerabilities` (netpack.pt/vaitp) carries a
`VulnerableCodeSample` / `PatchedCodeSample` pair produced by the enrichment agent on
the VM (`vaitp_vulnerability_info_api_gemini.py`). Those two fields are not decorative:
`RAGComponent.build_context_from_results` (orchestration/injection_agents.py:60) pastes
description + patched code + vulnerable code for the top-3 FAISS hits straight into the
planner prompt, inside an 8K-token window that must also hold the target source file and
the meta-prompt. So a sample that is a 400-line demo harness silently truncates the code
the planner is supposed to reason about, and a pair whose two halves share no structure
teaches the model nothing about the defect.

The samples were generated by two independent prompts ("show the code before the fix",
"show the code after the fix") with no shared context, which produces four recurring
defects, all present in the live snapshot:

  * prose contamination — markdown fences, "The user provided a fake CVE number...",
    "a direct Python fix does not exist, however..." (86 records carry ``` fences)
  * refusals stored as data — "I cannot provide a code example..." (15 records)
  * bulk — 152 vulnerable samples over 4000 chars, patched samples up to 16 KB, mostly
    exploit drivers, certificate factories and print() narration
  * non-corresponding pairs — different class names, different helper functions, so the
    vulnerable→patched delta is not extractable

This script walks the table newest-first, asks Claude Opus 5 to judge each pair against
the RAG rubric below, and rewrites only the pairs that fail. It runs to a **daily quota**
(10 records/day by default) so the corpus is revised slowly enough to stay reviewable, and
it is resumable: every decision (before, after, verdict, reasons, token usage) is appended
to a JSONL audit trail, the quota is counted from that trail so restarts and re-runs cannot
overshoot it, and `--restore` can roll any subset back.

Usage
-----
    # 1. see what would change, no writes
    python scripts/rag_code_quality_pass.py --limit 10

    # 2. today's ten, then exit — the shape to put in cron/launchd
    python scripts/rag_code_quality_pass.py --apply --resume

    # 3. leave it running: ten a day, evenly spread, sleeping through to the next day
    python scripts/rag_code_quality_pass.py --apply --resume --daemon

    # 4. ignore the quota and run flat out
    python scripts/rag_code_quality_pass.py --apply --resume --daily-quota 0

    # 5. undo
    python scripts/rag_code_quality_pass.py --restore results/rag_code_pass.jsonl --apply

At 10/day the ~1700 Python-flagged records take about six months; `--daily-quota` and
`--min-interval` are the two dials if that is too slow.

Credentials are read from the environment (ANTHROPIC_API_KEY, MYSQL_HOST, MYSQL_USER,
MYSQL_PASSWORD, MYSQL_DATABASE), from a .env in the framework root, or from a
my.cnf-style file passed with --db-config.
"""

