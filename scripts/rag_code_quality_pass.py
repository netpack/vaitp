def append_audit(path: str, entry: dict) -> None:
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "a", encoding="utf-8") as fh:
        fh.write(json.dumps(entry, ensure_ascii=False) + "\n")


def read_audit(path: str) -> list[dict]:
    if not os.path.isfile(path):
        return []
    entries = []
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if line:
                entries.append(json.loads(line))
    return entries


def processed_ids(path: str) -> set[int]:
    return {e["id"] for e in read_audit(path) if e.get("status") in ("pass", "rewrite")}


# A decision that consumed a model call counts against the daily quota. Plain "error"
# entries (connection blips, unexpected exceptions) do not, so a bad network moment
# cannot silently eat the day's allowance.
QUOTA_STATUSES = ("pass", "rewrite", "refused", "failed")


def count_done_today(path: str) -> int:
    """How many quota-consuming decisions the audit log already holds for today, local time."""
    today = datetime.now().astimezone().date()
    done = 0
    for entry in read_audit(path):
        if entry.get("status") not in QUOTA_STATUSES:
            continue
        stamp = entry.get("timestamp")
        if not stamp:
            continue
        try:
            when = datetime.fromisoformat(stamp).astimezone().date()
        except ValueError:
            continue
        if when == today:
            done += 1
    return done


def sleep_until_next_midnight() -> None:
    """Block until the local calendar day rolls over, in chunks so Ctrl-C stays responsive."""
    now = datetime.now().astimezone()
    tomorrow = now.replace(hour=0, minute=0, second=30, microsecond=0) + timedelta(days=1)
    remaining = (tomorrow - now).total_seconds()
    print(f"\nDaily quota reached. Sleeping {remaining / 3600.0:.1f}h until "
          f"{tomorrow:%Y-%m-%d %H:%M} (Ctrl-C to stop; --resume picks up where this left off).")
    while remaining > 0:
        time.sleep(min(60.0, remaining))
        remaining = (tomorrow - datetime.now().astimezone()).total_seconds()


def restore(args, cfg: dict[str, str]) -> int:
    """Roll rewritten records back to the `before` snapshot in the audit log."""
    entries = [e for e in read_audit(args.restore) if e.get("status") == "rewrite"]
    if args.ids:
        wanted = {int(x) for x in args.ids.split(",")}
        entries = [e for e in entries if e["id"] in wanted]
    if not entries:
        print("Nothing to restore.")
        return 0

    # Later entries win, so replay oldest-first and keep the earliest `before` per ID.
    originals: dict[int, dict] = {}
    for entry in entries:
        originals.setdefault(entry["id"], entry["before"])

    print(f"Restoring {len(originals)} record(s) from {args.restore}"
          f"{'' if args.apply else ' (dry run — pass --apply to write)'}")
    if not args.apply:
        for record_id in sorted(originals):
            print(f"  would restore ID {record_id}")
        return 0

    conn = connect(cfg)
    try:
        for record_id, before in sorted(originals.items()):
            update_record(conn, record_id, before["vulnerable"], before["patched"])
            print(f"  restored ID {record_id}")
    finally:
        conn.close()
    return 0


