def prescan(vulnerable: str, patched: str) -> list[str]:
    """Cheap, obvious defects. Advisory only — the model makes the call."""
    findings: list[str] = []
    pair = {"vulnerable": vulnerable or "", "patched": patched or ""}

    for label, code in pair.items():
        if not code.strip():
            findings.append(f"{label}: empty")
            continue
        lowered = code.lower()
        if "```" in code:
            findings.append(f"{label}: markdown fence")
        if any(marker in lowered for marker in REFUSAL_MARKERS):
            findings.append(f"{label}: refusal or apology text")
        if len(code) > MAX_SAMPLE_CHARS:
            findings.append(f"{label}: {len(code)} chars (limit {MAX_SAMPLE_CHARS})")
        if code.count("\n") + 1 > MAX_SAMPLE_LINES:
            findings.append(f"{label}: {code.count(chr(10)) + 1} lines (limit {MAX_SAMPLE_LINES})")
        if '__main__' in code:
            findings.append(f"{label}: __main__ driver block")
        if re.search(r"^\s*print\(", code, re.MULTILINE):
            findings.append(f"{label}: print() narration")
        try:
            ast.parse(code)
        except SyntaxError:
            findings.append(f"{label}: does not parse as Python")

    if pair["vulnerable"].strip() and pair["vulnerable"].strip() == pair["patched"].strip():
        findings.append("pair: vulnerable and patched are identical")
    elif pair["vulnerable"].strip() and pair["patched"].strip():
        ratio = difflib.SequenceMatcher(None, pair["vulnerable"], pair["patched"]).ratio()
        if ratio < 0.45:
            findings.append(f"pair: structurally unrelated (similarity {ratio:.2f})")

    return findings or ["nothing"]


def validate_rewrite(vulnerable: str, patched: str) -> list[str]:
    """Hard gate on the model's output. Any finding here blocks the write."""
    errors: list[str] = []
    for label, code in (("vulnerable_code", vulnerable), ("patched_code", patched)):
        if not code or not code.strip():
            errors.append(f"{label} is empty")
            continue
        if "```" in code:
            errors.append(f"{label} contains a markdown fence")
        if any(marker in code.lower() for marker in REFUSAL_MARKERS):
            errors.append(f"{label} contains refusal or apology prose")
        if len(code) > MAX_SAMPLE_CHARS:
            errors.append(f"{label} is {len(code)} chars (limit {MAX_SAMPLE_CHARS})")
        if code.count("\n") + 1 > MAX_SAMPLE_LINES:
            errors.append(f"{label} is {code.count(chr(10)) + 1} lines (limit {MAX_SAMPLE_LINES})")
        try:
            ast.parse(code)
        except SyntaxError as exc:
            errors.append(f"{label} does not parse as Python: {exc}")

    if vulnerable and patched:
        if vulnerable.strip() == patched.strip():
            errors.append("vulnerable_code and patched_code are identical")
        if "# VULNERABLE:" not in vulnerable:
            errors.append("vulnerable_code is missing its '# VULNERABLE:' marker (R6)")
        if "# FIX:" not in patched:
            errors.append("patched_code is missing its '# FIX:' marker (R6)")
    return errors


