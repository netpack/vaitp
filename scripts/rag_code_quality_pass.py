@dataclass
class Usage:
    input_tokens: int = 0        # uncached remainder only — cache fields are separate
    output_tokens: int = 0
    cache_read: int = 0
    cache_write: int = 0
    requests: int = 0

    def add(self, usage: Any) -> None:
        self.requests += 1
        self.input_tokens += getattr(usage, "input_tokens", 0) or 0
        self.output_tokens += getattr(usage, "output_tokens", 0) or 0
        self.cache_read += getattr(usage, "cache_read_input_tokens", 0) or 0
        self.cache_write += getattr(usage, "cache_creation_input_tokens", 0) or 0

    def cost_usd(self) -> float:
        # claude-opus-5: $5 / MTok in, $25 / MTok out; cache reads ~0.1x, writes ~1.25x.
        return (
            self.input_tokens * 5.0
            + self.cache_read * 0.5
            + self.cache_write * 6.25
            + self.output_tokens * 25.0
        ) / 1e6


@dataclass
class Auditor:
    client: Any
    limiter: RateLimiter
    effort: str = "high"
    max_tokens: int = 16000
    max_attempts: int = 5
    usage: Usage = field(default_factory=Usage)
    use_fallbacks: bool = True

    def _request(self, messages: list[dict]) -> Any:
        """One API call with backoff. Rate-limit and overload errors are retried."""
        import anthropic

        for attempt in range(self.max_attempts):
            self.limiter.wait()
            try:
                kwargs: dict[str, Any] = dict(
                    model=MODEL,
                    max_tokens=self.max_tokens,
                    system=[{
                        "type": "text",
                        "text": SYSTEM_PROMPT,
                        "cache_control": {"type": "ephemeral"},
                    }],
                    messages=messages,
                    thinking={"type": "adaptive"},
                    output_config={
                        "effort": self.effort,
                        "format": {"type": "json_schema", "schema": RESPONSE_SCHEMA},
                    },
                )
                if self.use_fallbacks:
                    # A vulnerability corpus is exactly the shape that trips cyber
                    # classifiers; route a decline to Opus 4.8 instead of losing the row.
                    return self.client.beta.messages.create(
                        betas=["server-side-fallback-2026-07-01"],
                        extra_body={"fallbacks": "default"},
                        **kwargs,
                    )
                return self.client.messages.create(**kwargs)

            except anthropic.BadRequestError as exc:
                if self.use_fallbacks and "fallback" in str(exc).lower():
                    print("  ! server-side fallbacks unavailable; continuing without them")
                    self.use_fallbacks = False
                    continue
                raise
            except anthropic.RateLimitError as exc:
                retry_after = float(exc.response.headers.get("retry-after", 0) or 0)
                delay = retry_after or min(60.0 * (2 ** attempt), 600.0)
                print(f"  ! rate limited, sleeping {delay:.0f}s")
                time.sleep(delay + random.uniform(0, 5))
            except (anthropic.APIStatusError, anthropic.APIConnectionError) as exc:
                status = getattr(exc, "status_code", None)
                if status is not None and status < 500:
                    raise
                delay = min(20.0 * (2 ** attempt), 300.0)
                print(f"  ! transient API error ({exc.__class__.__name__}), retry in {delay:.0f}s")
                time.sleep(delay + random.uniform(0, 5))

        raise RuntimeError(f"giving up after {self.max_attempts} attempts")

    def audit(self, record: dict) -> dict:
        """Judge one record; retry once with the validator's complaint if the rewrite is bad."""
        vulnerable = record.get("VulnerableCodeSample") or ""
        patched = record.get("PatchedCodeSample") or ""
        prompt = USER_TEMPLATE.format(
            cve=record.get("CVE") or "unknown",
            cwe=record.get("CWE") or "unknown",
            category=record.get("Category") or "unknown",
            subcategory=record.get("Subcategory") or "unknown",
            impact=record.get("Impact") or "unknown",
            changein=record.get("ChangeIn") or "unknown",
            solution=(record.get("Solution") or "unknown")[:600],
            description=(record.get("VulnerabilityLongDescription") or "").strip()[:4000],
            vulnerable=vulnerable or "(empty)",
            patched=patched or "(empty)",
            vuln_len=len(vulnerable),
            vuln_lines=vulnerable.count("\n") + 1 if vulnerable else 0,
            patch_len=len(patched),
            patch_lines=patched.count("\n") + 1 if patched else 0,
            prescan="; ".join(prescan(vulnerable, patched)),
        )

        messages: list[dict] = [{"role": "user", "content": prompt}]

        for round_index in range(2):
            response = self._request(messages)
            self.usage.add(response.usage)

            if response.stop_reason == "refusal":
                category = getattr(getattr(response, "stop_details", None), "category", None)
                return {"status": "refused", "detail": f"stop_reason=refusal category={category}"}

            text = next((b.text for b in response.content if b.type == "text"), "")
            try:
                payload = json.loads(text)
            except json.JSONDecodeError:
                return {"status": "failed", "detail": "response was not valid JSON"}

            if payload.get("verdict") == "pass":
                return {"status": "pass", "issues": payload.get("issues", []),
                        "notes": payload.get("notes", "")}

            new_vuln = payload.get("vulnerable_code") or ""
            new_patch = payload.get("patched_code") or ""
            errors = validate_rewrite(new_vuln, new_patch)
            if not errors:
                return {
                    "status": "rewrite",
                    "issues": payload.get("issues", []),
                    "notes": payload.get("notes", ""),
                    "vulnerable_code": new_vuln.strip() + "\n",
                    "patched_code": new_patch.strip() + "\n",
                }

            if round_index == 0:
                messages += [
                    {"role": "assistant", "content": text},
                    {"role": "user", "content":
                        "Your rewrite was rejected by the validator:\n- "
                        + "\n- ".join(errors)
                        + "\n\nReturn a corrected pair in the same schema."},
                ]

        return {"status": "failed", "detail": "; ".join(errors)}


