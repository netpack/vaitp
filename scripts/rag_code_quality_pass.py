class RateLimiter:
    """Deliberately slow pacing: a floor between request starts plus a rolling RPM cap."""

    def __init__(self, min_interval: float, rpm: float, jitter: float = 0.15):
        self.min_interval = min_interval
        self.rpm = rpm
        self.jitter = jitter
        self._last_start = 0.0
        self._starts: deque[float] = deque()

    def wait(self) -> None:
        now = time.monotonic()
        delay = 0.0

        if self._last_start:
            delay = max(delay, self.min_interval - (now - self._last_start))

        if self.rpm > 0:
            window = 60.0
            while self._starts and now - self._starts[0] > window:
                self._starts.popleft()
            if len(self._starts) >= self.rpm:
                delay = max(delay, window - (now - self._starts[0]))

        if delay > 0:
            time.sleep(delay + random.uniform(0, self.jitter * self.min_interval))

        start = time.monotonic()
        self._last_start = start
        self._starts.append(start)


