FETCH_COLUMNS = (
    "ID, CVE, CWE, Category, Subcategory, Impact, ChangeIn, Solution, "
    "VulnerabilityLongDescription, VulnerableCodeSample, PatchedCodeSample"
)


def connect(cfg: dict[str, str]):
    import pymysql

    return pymysql.connect(
        host=cfg["host"], user=cfg["user"], password=cfg["password"],
        database=cfg["database"], charset="utf8mb4",
        cursorclass=pymysql.cursors.DictCursor, connect_timeout=30,
    )


def fetch_records(conn, where: str, limit: int | None, ascending: bool) -> list[dict]:
    order = "ASC" if ascending else "DESC"
    sql = f"SELECT {FETCH_COLUMNS} FROM python_vulnerabilities WHERE {where} ORDER BY ID {order}"
    if limit:
        sql += f" LIMIT {int(limit)}"
    with conn.cursor() as cur:
        cur.execute(sql)
        return list(cur.fetchall())


def update_record(conn, record_id: int, vulnerable: str, patched: str) -> None:
    with conn.cursor() as cur:
        cur.execute(
            "UPDATE python_vulnerabilities SET VulnerableCodeSample = %s, "
            "PatchedCodeSample = %s WHERE ID = %s",
            (vulnerable, patched, record_id),
        )
    conn.commit()


def write_sample_files(files_dir: str, record_id: int, vulnerable: str, patched: str) -> None:
    """Mirror the enrichment agent's layout: patched -> injectable/, vulnerable -> noninjectable/."""
    for subdir, code in (("injectable", patched), ("noninjectable", vulnerable)):
        target_dir = os.path.join(files_dir, subdir)
        os.makedirs(target_dir, exist_ok=True)
        with open(os.path.join(target_dir, f"{record_id}_1.py"), "w", encoding="utf-8") as fh:
            fh.write(code)


